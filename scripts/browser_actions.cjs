const fs=require('fs');
const root=process.argv[2]||'artifacts/learned-actions';
const {chromium}=require(require.resolve('playwright',{paths:[process.env.CODEX_NODE_MODULES||'./preview/node_modules']}));
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'}),page=await browser.newPage({viewport:{width:1440,height:1000}}),errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://127.0.0.1:5173/');
 await page.locator('#score-file').setInputFiles(root+'/dcef4cf813abf326.json');
 await page.waitForFunction(()=>document.querySelector('#origin').textContent.includes('模型动作编排'));
 await page.locator('#timeline').fill('16');await page.locator('#timeline').dispatchEvent('input');
 const at=await page.locator('#stage canvas').screenshot();
 await page.locator('#timeline').fill('30');await page.locator('#timeline').dispatchEvent('input');
 if(at.equals(await page.locator('#stage canvas').screenshot()))throw Error('Action timeline did not change');
 await page.locator('#timeline').fill('16');await page.locator('#timeline').dispatchEvent('input');
 if(!at.equals(await page.locator('#stage canvas').screenshot()))throw Error('Seeking not reproducible');
 await page.screenshot({path:root+'/preview.png',fullPage:true});
 await page.locator('#offset').fill('0.3');await page.locator('#offset').dispatchEvent('input');
 if(at.equals(await page.locator('#stage canvas').screenshot()))throw Error('Layer edit had no effect');
 const download=page.waitForEvent('download');await page.locator('#save').click();await(await download).saveAs(root+'/edited.json');
 const saved=JSON.parse(fs.readFileSync(root+'/edited.json'));
 if(saved.entities[0].initial.x!==.3||saved.metadata.origin!=='learned_actions')throw Error('Export lost edit/origin');
 const rows=JSON.parse(fs.readFileSync(root+'/evaluation.json','utf8')).results;
 await page.locator('#audio-file').setInputFiles(rows[0].audio);
 await page.locator('#play').click();await page.waitForFunction(()=>Number(document.querySelector('#timeline').value)>16.5);await page.locator('#play').click();
 await page.setViewportSize({width:390,height:844});if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 console.log('Learned actions: provenance, deterministic seeking, distinct time frames, editing/export, audio playback, mobile layout passed');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
