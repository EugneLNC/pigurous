const fs=require('fs'),path=require('path');
const {chromium}=require(require.resolve('playwright',{paths:[path.resolve('preview/node_modules'),process.env.PLAYWRIGHT_MODULES].filter(Boolean)}));
(async()=>{
 const browser=await chromium.launch({headless:true,channel:'msedge'});
 const page=await browser.newPage({viewport:{width:1440,height:1040},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto(process.env.PREVIEW_URL||'http://127.0.0.1:5181/',{waitUntil:'networkidle'});
 await page.waitForFunction(()=>document.querySelector('#entity-count')?.textContent==='12');
 await page.locator('#timeline').fill('6');await page.locator('#timeline').dispatchEvent('input');
 const a=await page.locator('#stage canvas').screenshot();
 await page.locator('#timeline').fill('10');await page.locator('#timeline').dispatchEvent('input');
 const b=await page.locator('#stage canvas').screenshot();if(a.equals(b))throw Error('Orbit does not evolve');
 await page.locator('#timeline').fill('6');await page.locator('#timeline').dispatchEvent('input');
 if(!a.equals(await page.locator('#stage canvas').screenshot()))throw Error('Seeking is not deterministic');
 await page.getByRole('button',{name:'数学动作库',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#title')?.textContent?.includes('Harmonic Rose'));
 await page.locator('#timeline').fill('3');await page.locator('#timeline').dispatchEvent('input');
 fs.mkdirSync('docs/media',{recursive:true});await page.screenshot({path:'docs/media/workbench.png',fullPage:true});
 await page.locator('#offset').fill('0.15');await page.locator('#offset').dispatchEvent('input');
 const pending=page.waitForEvent('download');await page.locator('#save').click();const download=await pending;
 const location=await download.path();const saved=JSON.parse(fs.readFileSync(location,'utf8'));
 if(Math.abs(saved.entities[0].initial.x-.15)>1e-8)throw Error('Edit was not exported');
 await page.getByRole('button',{name:'九种动作素材',exact:true}).click();
 await page.waitForFunction(()=>document.querySelector('#entity-count')?.textContent==='9');
 await page.setViewportSize({width:390,height:844});
 if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw Error('Mobile overflow');
 if(errors.length)throw Error(errors.join('\n'));
 await browser.close();console.log('PASS: default fixture, motion, deterministic seeking, math/action examples, editing/export, responsive layout, screenshot, zero page errors');
})().catch(e=>{console.error(e);process.exit(1)});
